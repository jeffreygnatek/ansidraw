//! F1-F10 character sets, in the tradition of TheDraw/ACiDDraw.
//! ACiDDraw shipped 15 preset sets selectable with Alt-F1..F10 and
//! Ctrl-F1..F5; these defaults follow the common scene conventions.

pub const SETS: [(&str, [char; 10]); 15] = [
    ("Blocks", ['░', '▒', '▓', '█', '▀', '▄', '▌', '▐', '■', '·']),
    ("Single", ['┌', '┐', '└', '┘', '─', '│', '├', '┤', '┬', '┴']),
    ("Double", ['╔', '╗', '╚', '╝', '═', '║', '╠', '╣', '╦', '╩']),
    ("Mix SD", ['╒', '╕', '╘', '╛', '═', '│', '╞', '╡', '╤', '╧']),
    ("Mix DS", ['╓', '╖', '╙', '╜', '─', '║', '╟', '╢', '╥', '╨']),
    ("Cross",  ['┼', '╬', '╪', '╫', '▬', '▪', '□', '▫', '◊', '∙']),
    ("Dots",   ['·', '∙', '•', '○', '◘', '◙', '☺', '☻', '☼', '¤']),
    ("Arrows", ['↑', '↓', '→', '←', '↕', '↔', '▲', '▼', '►', '◄']),
    ("Suits",  ['♥', '♦', '♣', '♠', '♪', '♫', '♂', '♀', '‼', '¶']),
    ("Math",   ['±', '≥', '≤', '÷', '≈', '∞', '√', 'ⁿ', '²', '°']),
    ("Greek",  ['α', 'ß', 'Γ', 'π', 'Σ', 'σ', 'µ', 'τ', 'Φ', 'Θ']),
    ("Punct",  ['¡', '¿', 'ª', 'º', '«', '»', '½', '¼', '⌐', '¬']),
    ("Latin1", ['Ç', 'ü', 'é', 'â', 'ä', 'à', 'å', 'ç', 'ê', 'ë']),
    ("Latin2", ['É', 'æ', 'Æ', 'ô', 'ö', 'ò', 'û', 'ù', 'ÿ', '£']),
    ("Misc",   ['⌠', '⌡', '∩', '≡', '∟', '⌂', '₧', 'ƒ', '§', '▬']),
];

pub fn glyph(set: usize, fkey: usize) -> char {
    SETS[set % SETS.len()].1[fkey % 10]
}

pub fn name(set: usize) -> &'static str {
    SETS[set % SETS.len()].0
}
